[CmdletBinding()]
param(
    [switch] $VerifyOnly
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

if ($PSVersionTable.PSVersion.Major -lt 7) {
    throw 'Generation requires PowerShell 7 or later.'
}

$repoRoot = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$projectCount = 500
$layerCount = 20
$projectsPerLayer = 25
$referencesPerProject = 10
$projectReferenceCount = ($projectCount - $projectsPerLayer) * $referencesPerProject
$targetFramework = 'net10.0'
[long] $modulus = 1000000007
[long] $multiplier = 65599
[long] $seedMultiplier = 104729
[long] $saltMultiplier = 31
$configurationPlaceholder = '{configuration}'
$utf8 = [System.Text.UTF8Encoding]::new($false)
$expectedFiles = [System.Collections.Generic.Dictionary[string, string]]::new([System.StringComparer]::Ordinal)
$projects = [System.Collections.Generic.List[object]]::new()
$expectedValues = [long[]]::new($projectCount)

function ConvertTo-GeneratedText {
    param([Parameter(Mandatory)][string] $Text)

    return $Text.Replace("`r`n", "`n").TrimEnd("`r", "`n") + "`n"
}

for ($id = 0; $id -lt $projectCount; $id++) {
    $name = 'Project' + $id.ToString('D4', [System.Globalization.CultureInfo]::InvariantCulture)
    $layer = [int] [System.Math]::Floor($id / $projectsPerLayer)
    $indexInLayer = $id % $projectsPerLayer
    $isVerificationApp = $id -eq ($projectCount - 1)
    $outputType = if ($isVerificationApp) { 'Exe' } else { 'Library' }
    $dependencies = [System.Collections.Generic.List[int]]::new()

    if ($layer -gt 0) {
        $previousLayerStart = ($layer - 1) * $projectsPerLayer
        for ($offset = 0; $offset -lt $referencesPerProject; $offset++) {
            $dependencies.Add($previousLayerStart + (($indexInLayer + $offset) % $projectsPerLayer))
        }
    }

    $projectLines = [System.Collections.Generic.List[string]]::new()
    $projectLines.Add('<Project Sdk="Microsoft.NET.Sdk">')
    $projectLines.Add('  <PropertyGroup>')
    $projectLines.Add("    <OutputType>$outputType</OutputType>")
    $projectLines.Add('  </PropertyGroup>')
    if ($dependencies.Count -gt 0) {
        $projectLines.Add('  <ItemGroup>')
        foreach ($dependency in $dependencies) {
            $dependencyName = 'Project' + $dependency.ToString('D4', [System.Globalization.CultureInfo]::InvariantCulture)
            $projectLines.Add("    <ProjectReference Include=`"../$dependencyName/$dependencyName.csproj`" />")
        }
        $projectLines.Add('  </ItemGroup>')
    }
    $projectLines.Add('</Project>')
    $projectPath = "src/$name/$name.csproj"
    $expectedFiles.Add($projectPath, (ConvertTo-GeneratedText ($projectLines -join "`n")))

    # Values stay below 10^9 + 7. The largest intermediate is below 6.6 * 10^13,
    # so both PowerShell's Int64 arithmetic and C# checked arithmetic are exact.
    [long] $value = (($id + 1) * $seedMultiplier) % $modulus
    [long] $salt = ($id + 1) * $saltMultiplier
    $sourceLines = [System.Collections.Generic.List[string]]::new()
    $sourceLines.Add('// Generated by scripts/generate.ps1. Regenerate instead of editing.')
    $sourceLines.Add("namespace Pawel.MSBuildCacheTesting.$name;")
    $sourceLines.Add('')
    $sourceLines.Add('public static class WorkloadNode')
    $sourceLines.Add('{')
    $sourceLines.Add('    // A cached property preserves real assembly dependencies without repeated DAG evaluation.')
    $sourceLines.Add('    public static long Value { get; } = CalculateValue();')
    $sourceLines.Add('')
    $sourceLines.Add('    private static long CalculateValue()')
    $sourceLines.Add('    {')
    $sourceLines.Add('        checked')
    $sourceLines.Add('        {')
    $sourceLines.Add("            long value = $(($id + 1).ToString([System.Globalization.CultureInfo]::InvariantCulture))L * ${seedMultiplier}L % ${modulus}L;")
    for ($index = 0; $index -lt $dependencies.Count; $index++) {
        $dependency = $dependencies[$index]
        $dependencyName = 'Project' + $dependency.ToString('D4', [System.Globalization.CultureInfo]::InvariantCulture)
        $weight = $index + 1
        $value = (($value * $multiplier) + ($expectedValues[$dependency] * $weight) + $salt) % $modulus
        $sourceLines.Add("            value = ((value * ${multiplier}L) + (global::Pawel.MSBuildCacheTesting.$dependencyName.WorkloadNode.Value * ${weight}L) + ${salt}L) % ${modulus}L;")
    }
    $sourceLines.Add('            return value;')
    $sourceLines.Add('        }')
    $sourceLines.Add('    }')
    $sourceLines.Add('}')
    $expectedValues[$id] = $value
    $expectedFiles.Add("src/$name/WorkloadNode.cs", (ConvertTo-GeneratedText ($sourceLines -join "`n")))

    if ($isVerificationApp) {
        $program = @"
// Generated by scripts/generate.ps1. Regenerate instead of editing.
using System;
using Pawel.MSBuildCacheTesting.$name;

internal static class Program
{
    private static int Main()
    {
        const long expected = ${value}L;
        long actual = WorkloadNode.Value;
        if (actual != expected)
        {
            Console.Error.WriteLine(`$"Verification failed for ${name}: expected {expected}, actual {actual}.");
            return 1;
        }

        Console.WriteLine(`$"Verified ${name}: {actual}. Workload: $projectCount projects, $projectReferenceCount project references.");
        return 0;
    }
}
"@
        $expectedFiles.Add("src/$name/Program.cs", (ConvertTo-GeneratedText $program))
    }

    $projects.Add([ordered]@{
        id = $id
        name = $name
        layer = $layer
        indexInLayer = $indexInLayer
        path = $projectPath
        outputType = $outputType
        dependencies = @($dependencies.ToArray())
        expectedValue = $value
        assemblyPath = "artifacts/bin/$name/$configurationPlaceholder/$targetFramework/$name.dll"
    })
}

$verificationProject = $projects[$projectCount - 1]
$manifest = [ordered]@{
    schemaVersion = 1
    targetFramework = $targetFramework
    graph = [ordered]@{
        projectCount = $projectCount
        layerCount = $layerCount
        projectsPerLayer = $projectsPerLayer
        referencesPerProject = $referencesPerProject
        projectReferenceCount = $projectReferenceCount
        dependencyRule = 'Each node above layer 0 references offsets 0 through 9 of the previous layer, wrapping within its 25 nodes.'
    }
    arithmetic = [ordered]@{
        modulus = $modulus
        multiplier = $multiplier
        seedMultiplier = $seedMultiplier
        saltMultiplier = $saltMultiplier
        rule = 'Start at ((id + 1) * seedMultiplier) % modulus. For each dependency in order, value = (value * multiplier + dependencyValue * (index + 1) + (id + 1) * saltMultiplier) % modulus.'
    }
    strongFingerprintWorkload = [ordered]@{
        enabled = $true
        directoryMemberCount = 1000
        initializationMarkerPath = 'workload-inputs/.initialized'
        settingsPath = 'workload-inputs/settings.txt'
        settingsLines = @('workload-version=1', 'value=baseline-v1')
        membersDirectory = 'workload-inputs/members'
        markerDirectory = 'workload-inputs/markers'
        markerPath = 'workload-inputs/markers/{projectName}.marker'
        sidecarPath = 'artifacts/obj/{projectName}/{configuration}/net10.0/strong-fingerprint-observations.txt'
    }
    projects = @($projects.ToArray())
    verification = [ordered]@{
        projectId = $verificationProject.id
        projectPath = $verificationProject.path
        assemblyPath = $verificationProject.assemblyPath
        expectedValue = $verificationProject.expectedValue
    }
}
$expectedFiles.Add('workload.json', (ConvertTo-GeneratedText ($manifest | ConvertTo-Json -Depth 12)))

$unexpectedFiles = [System.Collections.Generic.List[string]]::new()
$srcRoot = Join-Path $repoRoot 'src'
if (Test-Path -LiteralPath $srcRoot) {
    foreach ($file in Get-ChildItem -LiteralPath $srcRoot -File -Recurse -Force) {
        $relativePath = [System.IO.Path]::GetRelativePath($repoRoot, $file.FullName).Replace('\', '/')
        if ($relativePath -match '/(bin|obj)/') {
            continue
        }
        if (-not $expectedFiles.ContainsKey($relativePath)) {
            $unexpectedFiles.Add($relativePath)
        }
    }
}

if ($unexpectedFiles.Count -gt 0) {
    foreach ($relativePath in $unexpectedFiles) {
        Write-Host "Unexpected generated-tree file: $relativePath"
    }
    throw 'The generated source tree contains unexpected files. Move or remove them explicitly before generating.'
}

$differences = [System.Collections.Generic.List[string]]::new()
[string[]] $relativePaths = @($expectedFiles.Keys)
[System.Array]::Sort($relativePaths, [System.StringComparer]::Ordinal)
foreach ($relativePath in $relativePaths) {
    $fullPath = Join-Path $repoRoot $relativePath
    $expectedText = $expectedFiles[$relativePath]
    $matches = (Test-Path -LiteralPath $fullPath -PathType Leaf) -and
        [System.StringComparer]::Ordinal.Equals([System.IO.File]::ReadAllText($fullPath).Replace("`r`n", "`n"), $expectedText)
    if ($matches) {
        continue
    }
    if ($VerifyOnly) {
        $differences.Add($relativePath)
    }
    else {
        $null = [System.IO.Directory]::CreateDirectory([System.IO.Path]::GetDirectoryName($fullPath))
        [System.IO.File]::WriteAllText($fullPath, $expectedText, $utf8)
    }
}

if ($differences.Count -gt 0) {
    foreach ($relativePath in $differences) {
        Write-Host "Generated content differs: $relativePath"
    }
    throw "Generated content is out of date in $($differences.Count) file(s). Run pwsh -NoProfile -File scripts/generate.ps1."
}

if ($VerifyOnly) {
    Write-Host "Verified generated content: $projectCount projects, $layerCount layers, $projectReferenceCount project references."
}
else {
    Write-Host "Generated $projectCount projects in $layerCount layers with $projectReferenceCount project references."
}
